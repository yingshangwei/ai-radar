/* Reproducible offline assets from the exact KaTeX version in pnpm-lock.yaml. */
const fs = require("node:fs");
const path = require("node:path");
const dist = path.dirname(require.resolve("katex"));
const root = path.dirname(dist);
const meta = JSON.parse(
  fs.readFileSync(path.join(root, "package.json"), "utf8"),
);
if (meta.version !== "0.18.7")
  throw new Error("Review the KaTeX version before regenerating assets");
const css = fs
  .readFileSync(path.join(dist, "katex.min.css"), "utf8")
  .replace(/src:([^;]+);/g, (all, sources) => {
    const match =
      /url\((?:['"])?(fonts\/[A-Za-z0-9_-]+\.woff2)(?:['"])?\)/.exec(sources);
    if (!match) throw new Error("Unexpected KaTeX font declaration");
    return (
      "src:url(data:font/woff2;base64," +
      fs.readFileSync(path.join(dist, match[1])).toString("base64") +
      ') format("woff2");'
    );
  });
if (/url\((?!data:)/.test(css))
  throw new Error("KaTeX still contains external font URLs");
const output =
  "// Generated by scripts/build-math-assets.cjs; do not edit.\n" +
  Object.entries({
    katexVersion: meta.version,
    katexCss: css,
    katexJs: fs.readFileSync(path.join(dist, "katex.min.js"), "utf8"),
    katexLicense: fs.readFileSync(path.join(root, "LICENSE"), "utf8"),
  })
    .map(
      ([key, value]) =>
        "export const " + key + " = " + JSON.stringify(value) + ";\n",
    )
    .join("");
const destination = path.join(__dirname, "../src/generated/katexAssets.ts");
fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, output);
console.log(
  "Bundled offline KaTeX " +
    meta.version +
    " (" +
    Buffer.byteLength(output) +
    " bytes)",
);
